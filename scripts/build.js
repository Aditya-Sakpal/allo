'use strict';
/** Bundles src/*.js into dist/Code.gs (single paste-ready file) and copies the manifest. */
const fs = require('fs');
const path = require('path');
const { bundleSource, sourceFiles } = require('../test/load');

const root = path.join(__dirname, '..');
const dist = path.join(root, 'dist');
fs.mkdirSync(dist, { recursive: true });
const header = `/**\n * Allo Recurring Tasks — Google Apps Script bundle (generated by \`npm run build\`, do not edit).\n` +
  ` * Source: src/ (${sourceFiles().join(', ')})\n * Paste into Extensions → Apps Script → Code.gs, save, then run setupSystem.\n */\n\n`;
fs.writeFileSync(path.join(dist, 'Code.gs'), header + bundleSource() + '\n');
fs.copyFileSync(path.join(root, 'src', 'appsscript.json'), path.join(dist, 'appsscript.json'));
console.log('dist/Code.gs and dist/appsscript.json written (' + fs.statSync(path.join(dist, 'Code.gs')).size + ' bytes)');
